// 生成 docs/modules.md：从 architecture-policy.yaml + package.json exports 派生的模块导航索引。
// 用法：
//   node scripts/docs/generate-module-index.mjs            打印到 stdout
//   node scripts/docs/generate-module-index.mjs --write    写入 docs/modules.md
// 此文件为生成产物，禁止手编；改动模块请改 architecture-policy.yaml 或包 package.json 后重跑 --write。

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { discoverFiles, loadPolicy, moduleForFile } from "../architecture/policy.mjs";
import { entryPointsFor, moduleDocPaths, moduleTestFiles } from "../architecture/index.mjs";

const root = path.resolve(import.meta.dirname, "../..");
export const MODULE_COVERAGE_THRESHOLD = 100;
const MODULE_DOC_PRIORITY = ["README.md", "README.zh.md", "AGENTS.md", "MODULE.md", "CONTRACT.md"];

/** 选出模块的主卡片（优先 README，其次 AGENTS/MODULE/CONTRACT），返回相对 docs/ 的链接或 null。 */
function primaryCard(docs) {
  for (const name of MODULE_DOC_PRIORITY) {
    const match = docs.find((doc) => doc.endsWith(`/${name}`) || doc === name);
    if (match) return match;
  }
  return null;
}

/** 收集每个模块的导航行。 */
async function moduleRows(policy, files, cwd) {
  const rows = [];
  for (const module of policy.modules) {
    const moduleFiles = files.filter((file) => moduleForFile(file, policy)?.id === module.id);
    const { entrypoints } = await entryPointsFor(module);
    const docs = await moduleDocPaths(module, cwd);
    const tests = await moduleTestFiles(module, cwd);
    const card = primaryCard(docs);
    const rootRel = module.roots.map((r) => r.replace(/\\/g, "/")).join(", ");
    const entry =
      entrypoints.length > 0
        ? `${entrypoints[0]}${entrypoints.length > 1 ? ` (+${entrypoints.length - 1})` : ""}`
        : "—";
    rows.push({
      id: module.id,
      owner: module.owner ?? "—",
      managed: module.managed,
      files: moduleFiles.length,
      roots: rootRel.replace(
        new RegExp(`^${cwd.replace(/\\/g, "/").replace(/[/\\^$.*+?()[\]{}|]/g, "\\$&")}/`),
        "",
      ),
      entry,
      card,
      tests: tests.length,
    });
  }
  return rows;
}

export async function generateModuleIndex({ cwd = root } = {}) {
  const policy = await loadPolicy(cwd);
  const files = await discoverFiles(policy);
  const rows = await moduleRows(policy, files, cwd);

  const tableHeader = "| Module | Owner | Files | Root | Public entry | Card |";
  const divider = "| --- | --- | --- | --- | --- | --- |";
  const tableRows = rows.map((row) => {
    const card = row.card ? `[card](../${row.card})` : "—";
    return `| ${row.id} | ${row.owner} | ${row.files} | ${row.roots} | ${row.entry} | ${card} |`;
  });

  const big = rows.filter((row) => row.files >= MODULE_COVERAGE_THRESHOLD);
  const bigWithCard = big.filter((row) => row.card).length;
  const coverageStatus =
    bigWithCard === big.length ? "passing" : `${bigWithCard}/${big.length} covered`;
  const cardsTotal = rows.filter((row) => row.card).length;

  const lines = [
    "<!-- GENERATED by `pnpm docs:modules --write`. Do not edit by hand. -->",
    "<!-- Edit modules in architecture-policy.yaml or package.json exports, then regenerate. -->",
    "",
    "# Module index",
    "",
    "Navigation map from capability to code. For a deep dive into one module, run `pnpm architecture:context <id>`; for hand-written orientation follow the card link.",
    "",
    tableHeader,
    divider,
    ...tableRows,
    "",
    "## Coverage",
    "",
    `- Cards present: ${cardsTotal}/${rows.length} modules.`,
    `- Coverage gate (≥${MODULE_COVERAGE_THRESHOLD} source files must have a card): ${coverageStatus}.`,
    `- Managed modules: ${rows.filter((row) => row.managed).length}/${rows.length}.`,
    "",
    "## How to use this index",
    "",
    "1. Find the module by capability or root path in the table above.",
    "2. Open the card link for orientation, or run `pnpm architecture:context <id>` for the directory map, entrypoints, tests and docs.",
    "3. Cross-module imports must go through the listed public entrypoint; see `architecture-policy.yaml` for declared dependencies and `AGENTS.md` for boundary rules.",
    "",
  ];
  return lines.join("\n");
}

// 仅在直接执行时输出/写入；被其他脚本 import 时不产生副作用。
const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const write = process.argv.includes("--write");
  const content = await generateModuleIndex();
  if (write) {
    const target = path.join(root, "docs/modules.md");
    await fs.writeFile(target, `${content}\n`);
    console.log(`wrote ${path.relative(root, target)}`);
  } else {
    console.log(content);
  }
}
